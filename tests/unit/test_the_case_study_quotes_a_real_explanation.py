"""The case study must quote an explanation the policy engine can produce.

## Why this file exists

``docs/case-study-duplicate-charge.md`` quotes the deterministic explanation
the policy engine wrote for the run it describes -- the sentence the approver
saw, the one the dashboard shows as the trustworthy half of the approval card.

That sentence is **generated by the code**, and the code changed: a commit
removed the currency from it, because it used to name a currency the money
would not move in. The document went on quoting the *new* sentence while the
run's own screenshot showed the *old* one -- so the document and its own
evidence disagreed, and nothing noticed. The document was not slightly out of
date; it attributed a sentence to a run that never produced it.

The rule this file keeps: a document that quotes a generated sentence must
quote one the generator can still produce -- **or** must say, with the commit
that changed it, that it is quoting the older one. A document that quotes a
sentence no code produces and names no commit is making a claim nobody can
check.

## What it does not do

It does not check that the run happened, or that the screenshot shows what
the document says. It checks the sentence against the generator, which is
the part that can be checked mechanically.
"""

from __future__ import annotations

import ast
import pathlib
import re

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
POLICIES = REPO_ROOT / "src" / "opspilot" / "domain" / "policies.py"
CASE_STUDY = REPO_ROOT / "docs" / "case-study-duplicate-charge.md"

#: A block quote: consecutive lines that start with ``>``. The explanation is
#: wrapped across two lines in the document, so the block is the unit, not the
#: line.
_QUOTED = re.compile(r"^((?:>[ \t]*.+\n?)+)", re.MULTILINE)

#: A commit id, which is what a historical sentence has to be labelled with.
_COMMIT = re.compile(r"`[0-9a-f]{7}`")


def _current_template() -> str:
    """The template the policy engine builds its explanation from.

    Read out of the source rather than transcribed, so a change to the
    template is a change to what this file compares against.
    """
    tree = ast.parse(POLICIES.read_text(encoding="utf-8"), filename=str(POLICIES.name))
    for node in ast.walk(tree):
        if not isinstance(node, ast.Return) or not isinstance(node.value, ast.JoinedStr):
            continue
        parts = [
            str(part.value)
            for part in node.value.values
            if isinstance(part, ast.Constant) and isinstance(part.value, str)
        ]
        text = "".join(parts)
        if "This moves" in text and "refunding transaction" in text:
            return text
    raise AssertionError(
        f"{POLICIES.name} no longer builds the sentence this document quotes; "
        "the comparison needs to know what the engine says now"
    )


def _matches(sentence: str, template: str) -> bool:
    """Whether a sentence is an instance of the template.

    The template's ``{placeholders}`` become "anything": the rendered amount
    and the transaction id are the run's, and the point is the *shape* of the
    sentence.
    """
    pattern = re.escape(template)
    pattern = re.sub(r"\\\{[a-z_]+\\\}", ".+?", pattern)
    return re.fullmatch(pattern, sentence) is not None


def _section_of(text: str, position: int) -> str:
    """The ``##`` section a position falls in."""
    headings = [match.start() for match in re.finditer(r"^## ", text, re.MULTILINE)]
    start = 0
    for heading in headings:
        if heading > position:
            break
        start = heading
    return text[start:position]


def test_every_quoted_explanation_is_one_the_engine_can_still_produce() -> None:
    """A quoted sentence, or a commit that explains why it is an old one."""
    text = CASE_STUDY.read_text(encoding="utf-8")
    template = _current_template()
    quoted = list(_QUOTED.finditer(text))
    assert quoted, (
        "the case study quotes no approval explanation; the sentence it "
        "attributes to the run is the one the approver read, and losing it "
        "would lose the only part of the run nobody can re-derive"
    )

    for match in quoted:
        lines = [line.strip().removeprefix(">").strip() for line in match.group(1).splitlines()]
        sentence = " ".join(lines).strip()
        if not sentence.startswith("This moves"):
            # Not the policy engine's sentence -- the case study quotes the
            # ticket, the tool calls and the approval row too.
            continue
        if _matches(sentence, template):
            continue
        section = _section_of(text, match.start())
        assert _COMMIT.search(section), (
            f"the case study quotes an explanation the policy engine does not "
            f"produce, and the section does not name the commit that changed "
            f"it:\n  {sentence!r}\n\nA sentence no code produces is a claim "
            "nobody can check."
        )


def test_the_engine_still_produces_a_sentence_with_the_currency_clause() -> None:
    """The current template names the currency.

    The commit that removed it was right -- the money moves in the
    transaction's own currency, and naming another one told the approver
    something false -- but it is a change to what the approver reads, so the
    shape of the sentence is worth pinning rather than assuming.
    """
    template = _current_template()
    assert "The amount is in the currency the transaction was charged in." in template
    assert "$" not in template, (
        "the explanation names a currency symbol; the transaction's own "
        "currency is not knowable here, and a symbol would be a guess"
    )
